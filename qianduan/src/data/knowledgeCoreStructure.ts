/**
 * 单章核心知识结构（图谱用）
 *
 * 图谱节点不再直接照搬教材小节标题，而是按"主题 → 核心知识点"两级提炼：
 *  - theme（主题）：由若干小节合并而成的知识单元，图谱中是蓝色节节点；
 *  - point（知识点）：该主题下真正的核心概念 / 方法 / 结论，节点标签经过精简，
 *    必要时把相邻小节合并为一个知识块（如"电场强度与叠加原理"）。
 *
 * point.id 必须取自 knowledgeGraphData.ts 中已存在的小节 id（偶尔也用只有一节的
 * 节 id，如 '1-8'），构建图谱时据此回查原小节标题，用于：
 *   1) 点击节点跳转到对应资料（lesson）；2) 悬浮卡片显示教材出处。
 * 这样既精简了节点，又不丢失与教材正文的对应关系。
 */

export interface CorePoint {
  /** 取自已存在的小节 / 节 id */
  id: string
  /** 提炼后的知识点标签（建议 ≤ 10 字） */
  label: string
  /** 必要补充：关键公式或一句话结论（缺省时用教材小节描述） */
  note?: string
}

export interface CoreTheme {
  /** 主题 id，形如 'c2-t1' */
  id: string
  /** 主题名（建议 ≤ 8 字） */
  label: string
  /** 该主题下合并了哪些教材小节（仅用于说明） */
  from?: string
  points: CorePoint[]
}

